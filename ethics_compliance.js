/**
 * Get audit log (for authorized users only)
 * @param {string} sessionId - Session identifier (for filtering)
 * @returns {Array} Audit log entries
 */
function getAuditLog(sessionId = null) {
  const normalizedSessionId = normalizeSessionId(sessionId);
  
  if (normalizedSessionId) {
    return AUDIT_LOG.filter(entry => entry.sessionId === normalizedSessionId);
  }
  
  return [...AUDIT_LOG]; // Return copy for immutability
}

/**
 * Clear audit log (for compliance with right to be forgotten)
 * @param {string} sessionId - Session identifier
 */
function clearAuditLog(sessionId = null) {
  const normalizedSessionId = normalizeSessionId(sessionId);
  
  if (normalizedSessionId) {
    // Remove entries for specific session
    for (let i = AUDIT_LOG.length - 1; i >= 0; i--) {
      if (AUDIT_LOG[i].sessionId === normalizedSessionId) {
        AUDIT_LOG.splice(i, 1);
      }
    }
  } else {
    // Clear all (admin only in production)
    AUDIT_LOG.length = 0;
  }
}

