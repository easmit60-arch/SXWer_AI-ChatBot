/**
 * Simplify text for cognitive accessibility
 * @param {string} text - Text to simplify
 * @returns {string} Simplified text
 */
function simplifyText(text) {
  if (!text || typeof text !== 'string') return text;
  
  // Replace complex words with simpler alternatives
  const simplifications = {
    'utilize': 'use',
    'individual': 'person',
    'commence': 'start',
    'terminate': 'end',
    'approximately': 'about',
    'however': 'but',
    'furthermore': 'also',
    'nevertheless': 'still',
    'consequently': 'so',
    'additionally': 'also',
  };
  
  let simplified = text;
  for (const [complex, simple] of Object.entries(simplifications)) {
    simplified = simplified.replace(new RegExp(`\\b${complex}\\b`, 'gi'), simple);
  }
  
  // Shorten long sentences
  const sentences = simplified.split('. ');
  simplified = sentences.map(sentence => {
    if (sentence.length > 20) {
      // Try to split long sentences
      const words = sentence.split(' ');
      if (words.length > 15) {
        const chunkSize = Math.ceil(words.length / 2);
        return words.slice(0, chunkSize).join(' ') + '. ' + words.slice(chunkSize).join(' ');
      }
    }
    return sentence;
  }).join('. ');
  
  return simplified;
}

