/**
 * Determine crisis escalation level
 * @param {string} input - User input
 * @param {Object} sensitivity - Sensitivity detection result
 * @returns {Object} Escalation level
 */
function determineCrisisEscalation(input, sensitivity) {
  if (sensitivity.category === 'crisis' && sensitivity.severity === 'imminent') {
    return CRISIS_ESCALATION_LEVELS.IMMEDIATE;
  }
  
  if (sensitivity.category === 'crisis' || 
      (sensitivity.category === 'mental_health' && sensitivity.severity === 'high')) {
    return CRISIS_ESCALATION_LEVELS.HIGH;
  }
  
  if (sensitivity.category === 'mental_health' && sensitivity.severity === 'medium') {
    return CRISIS_ESCALATION_LEVELS.MEDIUM;
  }
  
  return CRISIS_ESCALATION_LEVELS.LOW;
}

/**
 * Generate crisis response with escalation protocol
 * @param {string} input - User input
 * @param {Object} sensitivity - Sensitivity detection result
 * @param {Function} formatHumanNLP - Formatting function
 * @param {Function} truncateForMirror - Truncation function
 * @returns {Object} Formatted crisis response
 */
function generateCrisisResponseWithEscalation(input, sensitivity, formatHumanNLP, truncateForMirror) {
  const escalation = determineCrisisEscalation(input, sensitivity);
  
  return formatHumanNLP({
    userInput: input,
    anchor: escalation.message.split('.')[0] + '.', // First sentence as anchor
    mirror: `You shared: "${truncateForMirror(input, 50)}"`,
    reframe: `${escalation.message}`,
    rapport: escalation.humanSupport
      ? `Would you like me to connect you with a human crisis counselor now? (Reply "yes" for immediate help)`
      : `Would you like me to share more resources?`,
    isCrisis: true,
    escalationLevel: escalation.name,
    requiresHumanSupport: escalation.humanSupport,
    resources: escalation.resources,
  });
}

