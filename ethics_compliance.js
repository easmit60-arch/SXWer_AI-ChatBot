/**
 * Feedback store
 */
const FEEDBACK_STORE = [];

/**
 * Submit user feedback
 * @param {string} messageId - ID of the message being feedback on
 * @param {string} feedbackType - Type of feedback
 * @param {string} explanation - Optional explanation
 * @param {string} sessionId - Session identifier
 */
function submitFeedback(messageId, feedbackType, explanation = '', sessionId = null) {
  const normalizedSessionId = normalizeSessionId(sessionId);
  
  const feedback = {
    id: generateAnonymousSessionId(), // Anonymous feedback ID
    messageId,
    feedbackType,
    explanation,
    sessionId: normalizedSessionId,
    timestamp: new Date().toISOString(),
  };
  
  FEEDBACK_STORE.push(feedback);
  
  // Log for accountability
  logEthicalDecision('USER_FEEDBACK', {
    feedbackType,
    hasExplanation: explanation.length > 0,
  }, normalizedSessionId);
  
  return feedback;
}

/**
 * Get feedback for analysis
 * @param {string} sessionId - Optional session filter
 * @returns {Array} Feedback entries
 */
function getFeedback(sessionId = null) {
  const normalizedSessionId = normalizeSessionId(sessionId);
  
  if (normalizedSessionId) {
    return FEEDBACK_STORE.filter(f => f.sessionId === normalizedSessionId);
  }
  
  return [...FEEDBACK_STORE]; // Return copy
}

/**
 * Analyze feedback for ethical concerns
 * @returns {Object} Analysis report
 */
function analyzeFeedback() {
  const counts = {};
  const ethicalConcerns = [];
  
  for (const feedback of FEEDBACK_STORE) {
    // Count feedback types
    counts[feedback.feedbackType] = (counts[feedback.feedbackType] || 0) + 1;
    
    // Collect ethical concerns
    if (feedback.feedbackType === FEEDBACK_TYPES.ETHICAL_CONCERN ||
        feedback.feedbackType === FEEDBACK_TYPES.BIAS_CONCERN ||
        feedback.feedbackType === FEEDBACK_TYPES.SAFETY_CONCERN) {
      ethicalConcerns.push({
        type: feedback.feedbackType,
        explanation: feedback.explanation,
        timestamp: feedback.timestamp,
      });
    }
  }
  
  return {
    totalFeedback: FEEDBACK_STORE.length,
    counts,
    ethicalConcernsCount: ethicalConcerns.length,
    ethicalConcerns,
    timestamp: new Date().toISOString(),
  };
}

