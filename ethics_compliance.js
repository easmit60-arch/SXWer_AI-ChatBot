/**
 * Bias patterns for detection
 */
const BIAS_PATTERNS = Object.freeze({
  stereotypes: [
    /all\s+\w+\s+are/i,
    /every\s+\w+\s+is/i,
    /\w+\s+always\s+\w+/i,
    /\w+\s+never\s+\w+/i,
    /typical\s+\w+/i,
    /usually\s+\w+/i,
  ],
  generalizations: [
    /everyone\s+knows/i,
    /nobody\s+understands/i,
    /all\s+people\s+should/i,
    /most\s+people\s+would/i,
  ],
  assumptions: [
    /you\s+must\s+be/i,
    /you\s+probably/i,
    /i\s+assume\s+you/i,
    /of\s+course\s+you/i,
  ],
  harmful_stereotypes: [
    /\w+\s+for\s+a\s+\w+\s+is/i,
    /real\s+\w+\s+would/i,
    /a\s+true\s+\w+\s+would/i,
  ],
});

/**
 * Detect potential bias in text
 * @param {string} text - Text to analyze
 * @returns {Object} Bias detection result
 */
function detectBias(text) {
  if (!text || typeof text !== 'string') {
    return { hasBias: false, patterns: [], severity: 'none' };
  }
  
  const lowerText = text.toLowerCase();
  const detectedPatterns = [];
  
  // Check each bias pattern category
  for (const [category, patterns] of Object.entries(BIAS_PATTERNS)) {
    for (const pattern of patterns) {
      if (pattern.test(lowerText)) {
        detectedPatterns.push({ category, pattern: pattern.toString() });
      }
    }
  }
  
  if (detectedPatterns.length === 0) {
    return { hasBias: false, patterns: [], severity: 'none' };
  }
  
  // Determine severity based on number of matches
  const severity = detectedPatterns.length >= 3 ? 'high' : 
                   detectedPatterns.length >= 2 ? 'medium' : 'low';
  
  return { hasBias: true, patterns: detectedPatterns, severity };
}

/**
 * Mitigate bias in text
 * @param {string} text - Text to mitigate
 * @returns {string} Text with bias mitigation
 */
function mitigateBias(text) {
  if (!text || typeof text !== 'string') return text;
  
  let mitigated = text;
  
  // Replace absolute statements with qualified ones
  mitigated = mitigated.replace(/all\s+(\w+)/gi, 'many $1');
  mitigated = mitigated.replace(/every\s+(\w+)/gi, 'most $1');
  mitigated = mitigated.replace(/(\w+)\s+always\s+(\w+)/gi, '$1 often $2');
  mitigated = mitigated.replace(/(\w+)\s+never\s+(\w+)/gi, '$1 rarely $2');
  
  // Add disclaimers for assumptions
  mitigated = mitigated.replace(/you\s+must\s+be/i, 'you might be');
  mitigated = mitigated.replace(/you\s+probably/i, 'you may');
  
  return mitigated;
}

